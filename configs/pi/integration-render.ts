import assert from 'node:assert/strict';
import { Markdown, setCapabilities } from '@earendil-works/pi-tui';
import { getMarkdownTheme, initTheme } from '@earendil-works/pi-coding-agent';
import type { ExtensionAPI, MarkdownTransformer } from '@earendil-works/pi-coding-agent';
import { createMermaidMarkdownTransformer } from './node_modules/@earendil-works/pi-coding-agent/dist/modes/interactive/components/mermaid.js';
import visuals from './extensions/visuals.ts';

initTheme('dark', false);
setCapabilities({ images: 'kitty', trueColor: true, hyperlinks: true });
let transform: MarkdownTransformer | undefined;
visuals({ registerMarkdownTransformer: (value: MarkdownTransformer) => { transform = value; }, registerCommand: () => {}, on: () => {} } as unknown as ExtensionAPI);
const context = { messageType: 'assistant' as const, isStreaming: false, availableWidth: 80 };
const svg = 'Before\n\n```svg\n<svg xmlns="http://www.w3.org/2000/svg" width="40" height="20"><rect width="40" height="20" fill="currentColor"/></svg>\n```\n\nAfter';
const converted = transform!(svg, context);
const svgLines = new Markdown(converted, 0, 0, getMarkdownTheme()).render(80);
assert.ok(svgLines.some(line => line.includes('\x1b_G')), 'Native Markdown must preserve actual image protocol');
assert.ok(!converted.includes('```svg'));
assert.equal(converted.split('Before').length, 2);
const table = '| Label | Change |\n|---|---:|\n| Loss | -10 |\n| Gain | 10 |';
const chartLines = new Markdown(transform!(table, context), 0, 0, getMarkdownTheme()).render(80);
assert.ok(chartLines.some(line => /Loss.*−/.test(line)), 'Rendered chart must preserve negative values');
const mermaid = createMermaidMarkdownTransformer({ getMode: () => 'final' });
const diagramLines = new Markdown(mermaid('```mermaid\nflowchart LR\nA[Agent] --> B[Tool]\n```', context), 0, 0, getMarkdownTheme()).render(80);
assert.ok(diagramLines.some(line => line.includes('Agent') && line.includes('Tool')));
assert.ok(!diagramLines.join('\n').includes('flowchart'));
const xySource = '```mermaid\nxychart-beta\n title "O(n²) – Quadratic Growth"\n x-axis "Input size (n)" [1, 2, 3, 4, 5]\n y-axis "Operations" 0 --> 25\n line [1, 4, 9, 16, 25]\n```';
const xyLines = new Markdown(transform!(xySource, context), 0, 0, getMarkdownTheme()).render(80);
assert.ok(xyLines.some(line => line.includes('●')), 'XY plot contains rendered points');
assert.ok(xyLines.some(line => line.includes('Quadratic Growth')));
assert.ok(!xyLines.join('\n').includes('xychart-beta'));
const barLines = new Markdown(transform!(xySource.replace('line [', 'bar ['), context), 0, 0, getMarkdownTheme()).render(80);
assert.ok(barLines.some(line => line.includes('█')), 'Mermaid bar chart contains bars');
assert.ok(!barLines.join('\n').includes('xychart-beta'));
assert.ok(!xyLines.join('\n').includes('```'), 'Rendered charts do not show code fences');
console.log(xyLines.join('\n'));
console.log(JSON.stringify({ scenario: 'native-renderer', imageProtocolLines: svgLines.filter(line => line.includes('\x1b_G')).length, chartLines, diagramLines }, null, 2));
